-- No-cost abuse protection for the public consultation form. All writes are
-- performed by the homepage server with service_role; browsers have no access.

alter table public.inquiries
  add column if not exists submission_id uuid,
  add column if not exists contact_fingerprint text,
  add column if not exists sms_notification_status text;

create unique index if not exists inquiries_submission_id_unique
  on public.inquiries(submission_id)
  where submission_id is not null;
create index if not exists inquiries_contact_fingerprint_created_idx
  on public.inquiries(contact_fingerprint, created_at desc)
  where contact_fingerprint is not null;

create table if not exists public.inquiry_submission_claims (
  submission_id uuid primary key,
  status text not null default 'processing'
    check (status in ('processing', 'completed', 'blocked')),
  inquiry_id uuid references public.inquiries(id) on delete set null,
  contact_fingerprint text not null,
  ip_fingerprint text not null,
  browser_fingerprint text not null,
  reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inquiry_security_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (char_length(event_type) between 1 and 60),
  outcome text not null check (outcome in ('allowed', 'blocked', 'duplicate', 'warning')),
  reason text not null check (char_length(reason) between 1 and 100),
  submission_id uuid,
  ip_fingerprint text,
  contact_fingerprint text,
  browser_fingerprint text,
  details jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists inquiry_security_events_occurred_idx
  on public.inquiry_security_events(occurred_at desc);
create index if not exists inquiry_security_events_reason_idx
  on public.inquiry_security_events(reason, occurred_at desc);

alter table public.inquiry_submission_claims enable row level security;
alter table public.inquiry_security_events enable row level security;

revoke all on table public.inquiry_submission_claims from anon, authenticated;
revoke all on table public.inquiry_security_events from anon, authenticated;
grant select, insert, update, delete on table public.inquiry_submission_claims to service_role;
grant select, insert, delete on table public.inquiry_security_events to service_role;
grant usage, select on sequence public.inquiry_security_events_id_seq to service_role;

-- The existing rate-limit helper is SECURITY DEFINER, so it must not remain a
-- public RPC. Only the trusted homepage server may consume counters.
revoke execute on function public.consume_inquiry_rate_limit(text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.consume_inquiry_rate_limit(text, integer, integer)
  to service_role;

drop function if exists public.submit_inquiry(
  text, text, text, text, text, text, text, uuid, boolean
);

create or replace function public.submit_inquiry(
  p_name text,
  p_contact text,
  p_message text default null,
  p_source text default 'homepage',
  p_medium text default 'unknown',
  p_campaign text default 'unknown',
  p_content text default 'unknown',
  p_session_id uuid default null,
  p_clarity_ready boolean default false,
  p_submission_id uuid default null,
  p_contact_fingerprint text default null
)
returns uuid
language plpgsql
set search_path = public
as $$
declare rid uuid;
begin
  if btrim(coalesce(p_name, '')) = '' then raise exception 'NAME_REQUIRED' using errcode = 'P0010'; end if;
  if btrim(coalesce(p_contact, '')) = '' then raise exception 'CONTACT_REQUIRED' using errcode = 'P0011'; end if;
  if length(p_name) > 40 or length(p_contact) > 60 or length(coalesce(p_message,'')) > 1000 then
    raise exception 'TOO_LONG' using errcode = 'P0012';
  end if;

  if p_session_id is not null then
    insert into public.analytics_sessions(id, clarity_ready, clarity_ready_at)
    values (p_session_id, coalesce(p_clarity_ready, false),
            case when coalesce(p_clarity_ready, false) then now() else null end)
    on conflict (id) do update
      set last_seen_at = now(),
          clarity_ready = analytics_sessions.clarity_ready or excluded.clarity_ready,
          clarity_ready_at = coalesce(analytics_sessions.clarity_ready_at, excluded.clarity_ready_at);
  end if;

  insert into public.inquiries (
    name, contact, message, source, medium, campaign, content, session_id,
    clarity_ready, submission_id, contact_fingerprint
  ) values (
    btrim(p_name),
    btrim(p_contact),
    nullif(btrim(coalesce(p_message,'')), ''),
    left(coalesce(nullif(btrim(p_source), ''), 'unknown'), 100),
    left(coalesce(nullif(btrim(p_medium), ''), 'unknown'), 100),
    left(coalesce(nullif(btrim(p_campaign), ''), 'unknown'), 150),
    left(coalesce(nullif(btrim(p_content), ''), 'unknown'), 150),
    p_session_id,
    coalesce(p_clarity_ready, false),
    p_submission_id,
    nullif(left(btrim(coalesce(p_contact_fingerprint, '')), 128), '')
  ) returning id into rid;

  return rid;
end $$;

revoke execute on function public.submit_inquiry(
  text, text, text, text, text, text, text, uuid, boolean, uuid, text
) from public, anon, authenticated;
grant execute on function public.submit_inquiry(
  text, text, text, text, text, text, text, uuid, boolean, uuid, text
) to service_role;
