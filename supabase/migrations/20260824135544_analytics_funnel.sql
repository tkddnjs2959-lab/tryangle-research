-- First-party funnel analytics. Browser traffic is accepted only through the
-- homepage's server-side route; anon/authenticated never write these tables.

create table if not exists public.analytics_sessions (
  id uuid primary key,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  landing_path text,
  last_page_path text,
  referrer_host text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  utm_term text,
  last_utm_source text,
  last_utm_medium text,
  last_utm_campaign text,
  last_utm_content text,
  last_utm_term text,
  device_type text check (device_type is null or device_type in ('mobile', 'tablet', 'desktop')),
  browser_context text,
  clarity_ready boolean not null default false,
  clarity_ready_at timestamptz,
  max_scroll smallint not null default 0 check (max_scroll between 0 and 100)
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.analytics_sessions(id) on delete cascade,
  event_name text not null check (char_length(event_name) between 1 and 80),
  page_path text,
  properties jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists analytics_sessions_last_seen_idx
  on public.analytics_sessions(last_seen_at desc);
create index if not exists analytics_events_session_created_idx
  on public.analytics_events(session_id, created_at desc);
create index if not exists analytics_events_name_created_idx
  on public.analytics_events(event_name, created_at desc);

alter table public.analytics_sessions enable row level security;
alter table public.analytics_events enable row level security;

revoke all on table public.analytics_sessions from anon, authenticated;
revoke all on table public.analytics_events from anon, authenticated;
grant select, insert, update on table public.analytics_sessions to service_role;
grant select, insert on table public.analytics_events to service_role;
grant usage, select on sequence public.analytics_events_id_seq to service_role;

alter table public.inquiries
  add column if not exists session_id uuid references public.analytics_sessions(id) on delete set null,
  add column if not exists clarity_ready boolean not null default false;

create index if not exists inquiries_session_idx on public.inquiries(session_id);

create or replace function public.submit_inquiry(
  p_name text,
  p_contact text,
  p_message text default null,
  p_source text default 'homepage',
  p_medium text default 'unknown',
  p_campaign text default 'unknown',
  p_content text default 'unknown',
  p_session_id uuid default null,
  p_clarity_ready boolean default false
)
returns uuid
language plpgsql
set search_path = public
as $$
declare rid uuid;
begin
  if btrim(coalesce(p_name, '')) = '' then raise exception 'NAME_REQUIRED' using errcode = 'P0010'; end if;
  if btrim(coalesce(p_contact, '')) = '' then raise exception 'CONTACT_REQUIRED' using errcode = 'P0011'; end if;
  if length(p_name) > 40 or length(p_contact) > 60 or length(coalesce(p_message,'')) > 1000 then
    raise exception 'TOO_LONG' using errcode = 'P0012';
  end if;

  if p_session_id is not null then
    insert into public.analytics_sessions(id, clarity_ready, clarity_ready_at)
    values (p_session_id, coalesce(p_clarity_ready, false),
            case when coalesce(p_clarity_ready, false) then now() else null end)
    on conflict (id) do update
      set last_seen_at = now(),
          clarity_ready = analytics_sessions.clarity_ready or excluded.clarity_ready,
          clarity_ready_at = coalesce(analytics_sessions.clarity_ready_at, excluded.clarity_ready_at);
  end if;

  insert into public.inquiries (
    name, contact, message, source, medium, campaign, content, session_id, clarity_ready
  ) values (
    btrim(p_name),
    btrim(p_contact),
    nullif(btrim(coalesce(p_message,'')), ''),
    left(coalesce(nullif(btrim(p_source), ''), 'unknown'), 100),
    left(coalesce(nullif(btrim(p_medium), ''), 'unknown'), 100),
    left(coalesce(nullif(btrim(p_campaign), ''), 'unknown'), 150),
    left(coalesce(nullif(btrim(p_content), ''), 'unknown'), 150),
    p_session_id,
    coalesce(p_clarity_ready, false)
  ) returning id into rid;

  return rid;
end $$;

-- Avoid overloaded RPC ambiguity for clients still using the seven-argument call.
drop function if exists public.submit_inquiry(text, text, text, text, text, text, text);
